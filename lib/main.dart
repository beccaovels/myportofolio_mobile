import 'package:material_ui/material_ui.dart';
import 'package:myportofolio_mobile/screens/menu.dart';
import 'package:myportofolio_mobile/services/api_client.dart';
import 'package:myportofolio_mobile/services/auth_state.dart';
import 'package:provider/provider.dart';

void main() {
  runApp(MyApp(apiClient: ApiClient()));
}

/// Root widget of MyPortfolio Mobile.
///
/// [MultiProvider] injects the shared [ApiClient] and the [AuthState]
/// (login token) into the widget tree, so any screen can use
/// `context.read<ApiClient>()` or `context.watch<AuthState>()`.
/// [MaterialApp] provides the app-wide theme (indigo seed color with an
/// amber secondary), navigation, and Material defaults.
///
/// [apiClient] is a constructor parameter so tests can pass an [ApiClient]
/// backed by a fake HTTP client.
class MyApp extends StatelessWidget {
  const MyApp({required this.apiClient, super.key});

  final ApiClient apiClient;

  @override
  Widget build(BuildContext context) {
    return MultiProvider(
      providers: [
        Provider<ApiClient>.value(value: apiClient),
        ChangeNotifierProvider<AuthState>(create: (_) => AuthState(apiClient)),
      ],
      child: MaterialApp(
        title: 'MyPortfolio',
        theme: ThemeData(
          colorScheme: ColorScheme.fromSeed(
            seedColor: Colors.indigo,
            secondary: Colors.amber[700],
          ),
          useMaterial3: true,
        ),
        home: const MyHomePage(),
      ),
    );
  }
}
